st.header("5. 데이터 갱신 방법 (담당자용)")
st.markdown("""
1. 고객지원시스템에서 공동주택현황 CSV를 받아 `data/raw/공동주택현황.csv`에 덮어씁니다.
2. `python update_data.py` 실행 → 정제 · 좌표 · 단지 집계 · 시군구 · 고시지역 · K-apt 사용승인일까지 자동으로 처리합니다.
   (좌표·K-apt 결과는 `data/cache`에 누적되어 새 단지만 조회)
3. `streamlit run app.py`로 확인 후 GitHub에 커밋·푸시하면 사이트에 반영됩니다.

필요한 API 키 (`.env`): SGIS 서비스ID·비밀키, 공공데이터포털 일반 인증키(Decoding) —
'공동주택 단지 목록제공 서비스', '공동주택 기본 정보제공 서비스' 활용신청 필요.
""")
