"""데이터 안내 — 이 사이트가 어떤 데이터를 어떻게 연결해 만들었는지."""
import pandas as pd
import streamlit as st

from common import BULK_DATE, load_data

df = load_data()
apt = df[df["용도"] == "공동주택"]
n_bulk = int((df["공급승인일자"] == BULK_DATE).sum())
n_used = int(df["사용승인일"].notna().sum())

st.title("📖 데이터 안내")
st.caption("이 사이트는 당사 시스템 데이터에 외부 공공데이터를 연결해서 만들었습니다. "
           "각 항목이 어디서 왔고 무슨 뜻인지 정리한 페이지입니다.")

c1, c2, c3, c4 = st.columns(4)
c1.metric("전체 단지", f"{len(df):,}개")
c2.metric("공동주택", f"{len(apt):,}개")
c3.metric("1983 일괄등록", f"{n_bulk:,}개")
c4.metric("사용승인일 연결", f"{n_used:,}개")

# ─────────────────────────────────────────────────────────────
st.header("1. 데이터 출처")
st.markdown("""
| 구분 | 출처 | 가져오는 항목 |
|---|---|---|
| **당사 데이터** | 고객지원시스템 공동주택현황 (CSV) | 아파트명·아파트코드, 세대수, 난방구분, 용도·업종, 고객센터, 주소, **공급승인일자** |
| 외부 데이터 | 통계청 SGIS 지오코딩 API | 위도·경도, 행정동 (도로명주소 → 좌표) |
| 외부 데이터 | 지역난방 고시지역 경계 (GeoJSON) | 고시여부·고시지역명 (단지 좌표가 경계 안이면 '예') |
| 외부 데이터 | 국토교통부 공동주택관리정보시스템(K-apt) API | **사용승인일(준공)**, K-apt 단지명, K-apt 난방방식, 동수, 관리사무소 전화 |

모든 데이터는 **단지 단위**로 합쳐서 보여줍니다. 원본은 같은 단지라도 공급승인일자별로 행이 나뉘어 있어서
세대수를 합산하고, 대표 공급승인일자는 세대수가 가장 많은 행의 날짜를 씁니다.
""")

# ─────────────────────────────────────────────────────────────
st.header("2. 날짜 두 가지 — 공급승인일자 vs 사용승인일(준공)")
st.markdown("""
|  | **공급승인일자** | **사용승인일(준공)** |
|---|---|---|
| 의미 | 당사가 해당 단지에 **도시가스 공급을 승인한 날** | 건물이 완공되어 지자체로부터 **사용승인(준공)을 받은 날** |
| 출처 | 당사 고객지원시스템 | 국토교통부 K-apt (외부) |
| 기준 | 가스 공급 기준 | 건물 기준 |
| 범위 | 당사 공급 단지 전체 | K-apt 등록 단지만 (아래 4번 참고) |
| 쓰임 | 언제부터 우리 고객이었는지 | 건물이 얼마나 오래됐는지 (노후도·영업대상 판단) |

새로 짓는 단지는 두 날짜가 보통 비슷한 시기입니다. 다만 공급승인은 세대가 나중에 추가되면 날짜가 여러 개 생길 수 있고,
과거 공급분은 아래 이유로 실제 날짜가 없습니다. 그래서 **건물의 나이는 사용승인일**로 봅니다.
""")

st.subheader("왜 오래된 단지는 공급승인일자가 1983-01-01인가요?")
st.markdown(f"""
**1983-01-01은 실제 승인일이 아닙니다.** 고객지원시스템이 전산화되기 전에 이미 공급하고 있던 단지들을
시스템에 옮기면서 같은 날짜로 **일괄 등록**한 값입니다. 전산화 이전의 실제 승인일은 시스템에 남아 있지 않습니다.

- 현재 **{n_bulk:,}개** 단지가 1983-01-01로 되어 있습니다.
- 지도와 통계에서는 이 값을 **'1983 일괄등록'**으로 따로 표시합니다. '1983년에 공급승인'이라는 뜻이 아니라 **'그 이전부터 공급'**이라는 뜻입니다.
- 이 단지들의 실제 나이를 알려고 K-apt **사용승인일**을 연결했습니다.
""")

# ─────────────────────────────────────────────────────────────
st.header("3. 외부 데이터를 어떻게 연결했나")
st.markdown("""
**좌표 (SGIS)**: 도로명주소로 지오코딩합니다. 한 번 찾은 좌표는 캐시에 저장해서 다음부터는 새 단지만 조회합니다.
좌표를 못 찾은 단지(일부 지번 주소, 군 관련 시설 등)는 지도에서 빠집니다.

**사용승인일 (K-apt)**: 당사 아파트코드·단지명은 K-apt와 **서로 다릅니다** (예: 당사 '보성대덕아파트' = K-apt '1차대덕맨션').
그래서 **주소로 매칭**합니다.
1. 도로명주소가 같은 K-apt 단지 → 지번이 같은 단지 → 지번 본번이 같은 단지 순으로 찾습니다.
2. 같은 주소에 다른 건물(빌라·연립 등)이 함께 있을 수 있어서 **세대수가 0.5~2배 안이거나 단지명이 비슷한 경우만** 인정합니다.
   지번 본번만 같은 경우는 둘 다 맞아야 인정합니다.
3. 후보가 여럿이면 세대수가 가장 가까운 단지를 고릅니다.

어떤 방법으로 매칭됐는지는 상세정보·영업대상 목록의 **'매칭방법'**에서 볼 수 있습니다.
""")

# ─────────────────────────────────────────────────────────────
st.header("4. 알아둘 한계")
st.markdown(f"""
- **K-apt에는 의무관리대상 공동주택만 있습니다** (대략 300세대 이상, 또는 150세대 이상이면서 승강기·중앙/지역난방 등).
  소규모 아파트·연립·다세대·비주거 시설은 사용승인일이 **비어 있는 게 정상**입니다. (공동주택 {len(apt):,}개 중 {n_used:,}개 연결)
- 주소 매칭이라 드물게 잘못 붙거나 못 붙을 수 있습니다. 중요한 건은 'K-apt 단지명'과 '세대수'를 같이 확인해 주세요.
- **난방방식이 서로 다를 때**: 당사 난방구분과 K-apt 난방방식이 다르면 영업대상 페이지에서 '난방확인'으로 표시합니다.
  개별난방으로 전환했는데 당사 데이터에 반영이 안 됐을 수 있으니 확인이 필요합니다.
- 공공데이터 API는 하루 호출 한도가 있어서 처음 전체 조회는 며칠에 나눠 진행될 수 있습니다.
""")

